# Bentuk kembali matriks fitur dari df (tidak pakai X lagi)
X_all = df[numeric_features + categorical_features + [text_feature]]

# Transform semua data ke ruang fitur yang sudah di-preprocess
# (preprocessor sudah di-fit saat training KNN classifier di cell 6–7)
X_all_vec = preprocessor.transform(X_all)

# Bangun model KNN untuk recommender (unsupervised)
knn_recommender = NearestNeighbors(
    n_neighbors=11,   # 1 (dirinya sendiri) + 10 rekomendasi
    metric='cosine',
    algorithm='brute'
)
knn_recommender.fit(X_all_vec)

def recommend_knn(place_name, top_n=10):
    """
    KNN-based recommender:
    Mengembalikan top_n tempat wisata yang paling mirip dengan place_name
    berdasarkan fitur:
    - rating (distandarkan)
    - fee (distandarkan)
    - city (one-hot)
    - text (TF-IDF deskripsi + review)
    """
    # Cari index tempat berdasarkan nama
    mask = df['place'].str.lower() == place_name.lower()
    if not mask.any():
        raise ValueError(f"Tempat '{place_name}' tidak ditemukan di dataset.")

    idx = df[mask].index[0]

    # Ambil vektor fitur tempat tersebut
    place_vec = X_all_vec[idx]

    # Cari K tetangga terdekat (K = top_n + 1 karena termasuk dirinya sendiri)
    distances, indices = knn_recommender.kneighbors(place_vec, n_neighbors=top_n + 1)

    # Buang dirinya sendiri (indeks pertama)
    rec_indices = indices[0][1:]
    rec_distances = distances[0][1:]

    # Susun hasil dalam DataFrame
    recs = df.iloc[rec_indices][['place', 'city', 'category', 'rating', 'fee', 'link']].copy()
    recs['similarity'] = 1 - rec_distances  # cosine similarity = 1 - distance

    # Urutkan dari kemiripan tertinggi
    recs = recs.sort_values(by='similarity', ascending=False)

    return recs

