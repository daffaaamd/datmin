# Fungsi Evaluasi KNN (Akurasi, Precision, Recall, F1)

def evaluate_knn(n_neighbors, weights='uniform', metric='minkowski', p=2):
    """
    Evaluasi model KNN dengan pipeline preprocessing.
    Mengembalikan: akurasi, precision, recall, f1, dan model terlatih.
    """
    clf = Pipeline(steps=[
        ('preprocess', preprocessor),
        ('model', KNeighborsClassifier(
            n_neighbors=n_neighbors,
            weights=weights,
            metric=metric,
            p=p
        ))
    ])

    clf.fit(X_train, y_train)
    y_pred = clf.predict(X_test)

    acc  = accuracy_score(y_test, y_pred)
    prec = precision_score(y_test, y_pred, average='macro', zero_division=0)
    rec  = recall_score(y_test, y_pred, average='macro', zero_division=0)
    f1   = f1_score(y_test, y_pred, average='macro', zero_division=0)

    return acc, prec, rec, f1, clf

